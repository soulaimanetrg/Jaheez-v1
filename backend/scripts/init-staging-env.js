'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { REQUIRED_ENV, PLACEHOLDER_ENV_RULES } = require('./production-readiness-preflight');

const backendRoot = path.resolve(__dirname, '..');
const envPath = path.join(backendRoot, '.env.staging.local');
const examplePath = path.join(backendRoot, '.env.staging.local.example');

const ALWAYS_SAFE_VALUES = {
  JAHEEZ_TARGET_ENV: 'staging',
  STAGING_CONFIRM_ISOLATED: 'true',
  OUTBOUND_INTEGRATIONS_DISABLED: 'true',
  ONLINE_PAYMENTS_ENABLED: 'false',
  PAYMENT_PROVIDER: 'disabled',
};

function parseEnv(text) {
  const values = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) values.set(match[1], match[2]);
  }
  return values;
}

function isPlaceholder(key, value) {
  if (!value) return true;
  const rule = PLACEHOLDER_ENV_RULES.find((item) => item.key === key);
  return Boolean(rule && rule.pattern.test(String(value).trim()));
}

function decodesTo32ByteKey(value) {
  if (!value) return false;
  try {
    const trimmed = String(value).trim();
    const parsed = /^[0-9a-f]{64}$/i.test(trimmed) ? Buffer.from(trimmed, 'hex') : Buffer.from(trimmed, 'base64');
    return parsed.length === 32;
  } catch {
    return false;
  }
}

function buildEnv() {
  if (!fs.existsSync(examplePath)) throw new Error('backend/.env.staging.local.example is missing.');

  const example = parseEnv(fs.readFileSync(examplePath, 'utf8'));
  const current = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : new Map();
  const generatedKeys = [];
  const missingExternal = [];
  const out = [];

  out.push('# JAHEEZ private staging validation environment');
  out.push('# Generated by npm run staging:init-env. Do not commit this file.');
  out.push('');

  for (const key of REQUIRED_ENV) {
    let value = current.has(key) ? current.get(key) : example.get(key);

    if (Object.prototype.hasOwnProperty.call(ALWAYS_SAFE_VALUES, key)) {
      value = ALWAYS_SAFE_VALUES[key];
    }

    if (key === 'BACKUP_ENCRYPTION_KEY' && (!decodesTo32ByteKey(value) || isPlaceholder(key, value))) {
      value = crypto.randomBytes(32).toString('hex');
      generatedKeys.push(key);
    }

    if (key === 'REPORT_SIGNING_KEY' && (!value || value.length < 32 || isPlaceholder(key, value))) {
      value = crypto.randomBytes(32).toString('hex');
      generatedKeys.push(key);
    }

    if (key === 'ADMIN_JWT_SECRET' && (!value || value.length < 32 || isPlaceholder(key, value))) {
      value = crypto.randomBytes(32).toString('hex');
      generatedKeys.push(key);
    }

    if (!Object.prototype.hasOwnProperty.call(ALWAYS_SAFE_VALUES, key) &&
      key !== 'BACKUP_ENCRYPTION_KEY' &&
      key !== 'REPORT_SIGNING_KEY' &&
      key !== 'ADMIN_JWT_SECRET' &&
      isPlaceholder(key, value)) {
      missingExternal.push(key);
    }

    out.push(`${key}=${value || ''}`);
  }

  return { text: `${out.join('\n')}\n`, generatedKeys, missingExternal };
}

function main() {
  const { text, generatedKeys, missingExternal } = buildEnv();

  fs.writeFileSync(envPath, text, { mode: 0o600 });
  try { fs.chmodSync(envPath, 0o600); } catch { /* Best effort on Windows. */ }

  console.log(JSON.stringify({
    ok: true,
    env_file: path.relative(process.cwd(), envPath),
    generated_secret_fields: generatedKeys,
    missing_external_fields: missingExternal,
    online_payments_enabled: false,
    payment_provider: 'disabled',
    note: 'Secret values were written locally but not printed.',
  }, null, 2));
}

main();
