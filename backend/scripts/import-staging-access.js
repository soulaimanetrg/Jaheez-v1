'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { evaluateReadiness, PLACEHOLDER_ENV_RULES, REQUIRED_ENV } = require('./production-readiness-preflight');

const backendRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(backendRoot, '..');
const envPath = path.join(backendRoot, '.env.staging.local');
const defaultAccessPath = path.join(backendRoot, 'staging-access.private.json');

const ALWAYS_SAFE_VALUES = {
  JAHEEZ_TARGET_ENV: 'staging',
  STAGING_CONFIRM_ISOLATED: 'true',
  OUTBOUND_INTEGRATIONS_DISABLED: 'true',
  ONLINE_PAYMENTS_ENABLED: 'false',
  PAYMENT_PROVIDER: 'disabled',
};

const GENERATED_KEYS = new Set([
  'BACKUP_ENCRYPTION_KEY',
  'REPORT_SIGNING_KEY',
  'ADMIN_JWT_SECRET',
]);

function parseEnv(text) {
  const values = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) values.set(match[1], match[2]);
  }
  return values;
}

function quoteEnv(value) {
  const text = String(value || '');
  if (!/[#\s"'\\]/.test(text)) return text;
  return JSON.stringify(text);
}

function normalizeObjectKeys(input) {
  const out = new Map();
  if (!input || typeof input !== 'object' || Array.isArray(input)) return out;
  for (const [key, value] of Object.entries(input)) {
    out.set(String(key).trim().toUpperCase(), typeof value === 'string' ? value.trim() : value);
  }
  return out;
}

function isPlaceholder(key, value) {
  if (!value) return true;
  const rule = PLACEHOLDER_ENV_RULES.find((item) => item.key === key);
  return Boolean(rule && rule.pattern.test(String(value).trim()));
}

function decodesTo32ByteKey(value) {
  if (!value) return false;
  try {
    const trimmed = String(value).trim();
    const parsed = /^[0-9a-f]{64}$/i.test(trimmed) ? Buffer.from(trimmed, 'hex') : Buffer.from(trimmed, 'base64');
    return parsed.length === 32;
  } catch {
    return false;
  }
}

function generateIfNeeded(key, value) {
  if (key === 'BACKUP_ENCRYPTION_KEY' && (!decodesTo32ByteKey(value) || isPlaceholder(key, value))) {
    return crypto.randomBytes(32).toString('hex');
  }
  if ((key === 'REPORT_SIGNING_KEY' || key === 'ADMIN_JWT_SECRET') && (!value || String(value).length < 32 || isPlaceholder(key, value))) {
    return crypto.randomBytes(32).toString('hex');
  }
  return value || '';
}

function loadAccess(file) {
  if (!fs.existsSync(file)) {
    throw new Error(`Missing private access file: ${file}\nCopy backend/staging-access.private.json.example to backend/staging-access.private.json and fill real values.`);
  }
  try {
    return normalizeObjectKeys(JSON.parse(fs.readFileSync(file, 'utf8')));
  } catch (error) {
    throw new Error(`Invalid JSON in ${file}: ${error.message}`);
  }
}

function resolveAccessPath(raw) {
  if (!raw) return defaultAccessPath;
  if (path.isAbsolute(raw)) return raw;
  const candidates = [
    path.resolve(process.cwd(), raw),
    path.resolve(backendRoot, raw),
    path.resolve(repoRoot, raw),
  ];
  return candidates.find((candidate) => fs.existsSync(candidate)) || candidates[0];
}

function writeEnv(access) {
  const current = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : new Map();
  const out = [
    '# JAHEEZ private staging validation environment',
    '# Generated by npm run staging:import-access. Do not commit this file.',
    '',
  ];
  const imported = [];
  const skippedPlaceholders = [];
  const missingExternal = [];

  for (const key of REQUIRED_ENV) {
    let value = current.get(key) || '';

    if (Object.prototype.hasOwnProperty.call(ALWAYS_SAFE_VALUES, key)) {
      value = ALWAYS_SAFE_VALUES[key];
    } else if (GENERATED_KEYS.has(key)) {
      value = generateIfNeeded(key, value);
    } else if (access.has(key)) {
      const candidate = access.get(key);
      if (candidate && !isPlaceholder(key, candidate)) {
        value = String(candidate).trim();
        imported.push(key);
      } else {
        skippedPlaceholders.push(key);
        value = current.get(key) && !isPlaceholder(key, current.get(key)) ? current.get(key) : '';
      }
    }

    if (!Object.prototype.hasOwnProperty.call(ALWAYS_SAFE_VALUES, key) &&
      !GENERATED_KEYS.has(key) &&
      (!value || isPlaceholder(key, value))) {
      missingExternal.push(key);
      value = '';
    }

    out.push(`${key}=${quoteEnv(value)}`);
  }

  fs.writeFileSync(envPath, `${out.join('\n')}\n`, { mode: 0o600 });
  try { fs.chmodSync(envPath, 0o600); } catch { /* Best effort on Windows. */ }

  return { imported, skippedPlaceholders, missingExternal };
}

function main() {
  const accessPath = resolveAccessPath(process.argv[2]);
  const access = loadAccess(accessPath);
  const result = writeEnv(access);
  const readiness = evaluateReadiness();

  console.log(JSON.stringify({
    ok: result.missingExternal.length === 0 && readiness.ok,
    env_file: path.relative(process.cwd(), envPath),
    imported_keys: result.imported.sort(),
    skipped_placeholder_keys: result.skippedPlaceholders.sort(),
    missing_external_fields: result.missingExternal,
    preflight_passed: readiness.passed,
    preflight_failed: readiness.failed,
    note: 'Secret values were written locally but not printed.',
  }, null, 2));

  process.exit(readiness.ok ? 0 : 2);
}

main();
